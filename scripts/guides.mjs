const NO_GUARANTOR_RE = [
  /без\s+(?:обезбедување|жиранти?)[^.;]*?до\s+([\d.]+)/i, // „Без обезбедување до 1.500.000“, „без жиранти до 2.000.000“
  /до\s+([\d.]+)\s+без\s+[^.;]*жирант/i,                  // „До 900.000 без нотар, жиранти …“
];
function noGuarantorLimit(i) {
  for (const re of NO_GUARANTOR_RE) {
    const m = (i.notes || '').match(re);
    if (m) return Number(m[1].replace(/\./g, ''));
  }
  return null;
}
const ngKey = (i) => i.name.toLowerCase();
