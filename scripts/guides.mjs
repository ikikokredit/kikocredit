// Месечна рата со СВТ земена како годишна стапка — иста математика како калкулаторот.
function plan(amount, svt, months) {
  const r = svt / 100 / 12;
  const payment = r === 0 ? amount / months : amount * r / (1 - Math.pow(1 + r, -months));
  const total = Math.round(payment * months);
  return { payment: Math.round(payment), total, cost: total - amount };
}

// Вистинска СВТ од паричните текови (месечна внатрешна стапка → годишна).
function aprOf(net, flows) {
  let lo = 0, hi = 1;
  for (let k = 0; k < 200; k++) {
    const m = (lo + hi) / 2;
    const pv = flows.reduce((s, [t, a]) => s + a / Math.pow(1 + m, t), 0);
    if (pv > net) lo = m; else hi = m;
  }
  return (Math.pow(1 + lo, 12) - 1) * 100;
}

